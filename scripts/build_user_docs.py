# markdown
# ---------------------------------------------------------------------------

class MarkdownRenderer:
    def __init__(self, pages_by_name: dict[str, "Page"]):
        self.pages_by_name = pages_by_name

    def render(self, source: str) -> tuple[str, list[tuple[int, str, str]]]:
        lines = source.splitlines()
        out: list[str] = []
        headings: list[tuple[int, str, str]] = []
        used_ids: set[str] = set()

        def heading_id(text: str) -> str:
            base = slugify(text)
            candidate = base
            counter = 2
            while candidate in used_ids:
                candidate = f"{base}-{counter}"
                counter += 1
            used_ids.add(candidate)
            return candidate

        paragraph: list[str] = []
        list_items: list[tuple[int, str]] = []
        list_type: str | None = None
        quote: list[str] = []

        def flush_paragraph() -> None:
            nonlocal paragraph
            if paragraph:
                out.append(f"<p>{' '.join(paragraph)}</p>")
                paragraph = []

        def flush_list() -> None:
            nonlocal list_items, list_type
            if not list_items:
                list_type = None
                return
            # build nested list by indentation depth
            tag = list_type or "ul"
            html_parts: list[str] = []
            stack: list[int] = []
            for depth, item in list_items:
                while stack and depth < stack[-1]:
                    html_parts.append(f"</li></{tag}>")
                    stack.pop()
                if not stack or depth > stack[-1]:
                    html_parts.append(f"<{tag}>")
                    stack.append(depth)
                    html_parts.append(f"<li>{item}")
                else:
                    html_parts.append(f"</li><li>{item}")
            while stack:
                html_parts.append(f"</li></{tag}>")
                stack.pop()
            out.append("".join(html_parts))
            list_items = []
            list_type = None

        def flush_quote() -> None:
            nonlocal quote
            if quote:
                body = " ".join(quote)
                out.append(f'<blockquote><p>{body}</p></blockquote>')
                quote = []

        i = 0
        while i < len(lines):
            line = lines[i]

            fence = re.match(r"^```(\w*)\s*$", line)
            if fence:
                flush_paragraph()
                flush_list()
                flush_quote()
                lang = fence.group(1)
                i += 1
                code_lines: list[str] = []
                while i < len(lines) and not lines[i].startswith("```"):
                    code_lines.append(lines[i])
                    i += 1
                i += 1
                code = html.escape("\n".join(code_lines), quote=False)
                cls = f' class="language-{lang}"' if lang else ""
                out.append(f"<pre><code{cls}>{code}</code></pre>")
                continue

            if not line.strip():
                flush_paragraph()
                flush_list()
                flush_quote()
                i += 1
                continue

            heading = re.match(r"^(#{1,4})\s+(.*)$", line)
            if heading:
                flush_paragraph()
                flush_list()
                flush_quote()
                level = len(heading.group(1))
                text = inline(heading.group(2).strip())
                hid = heading_id(heading.group(2).strip())
                if level > 1:
                    headings.append((level, heading.group(2).strip(), hid))
                out.append(f'<h{level} id="{hid}">{text}</h{level}>')
                i += 1
                continue

            if re.match(r"^---+$", line.strip()):
                flush_paragraph()
                flush_list()
                flush_quote()
                out.append("<hr>")
                i += 1
                continue

            if line.startswith(">"):
                flush_paragraph()
                flush_list()
                quote.append(inline(line.lstrip("> ").strip()))
                i += 1
                continue

            bullet = re.match(r"^(\s*)[-*]\s+(.*)$", line)
            numbered = re.match(r"^(\s*)\d+\.\s+(.*)$", line)
            if bullet or numbered:
                flush_paragraph()
                flush_quote()
                kind = "ul" if bullet else "ol"
                if list_type is not None and list_type != kind:
                    flush_list()
                list_type = kind
                match = bullet or numbered
                list_items.append((len(match.group(1)), inline(match.group(2).strip())))
                i += 1
                continue

            # continuation of the previous list item (indented, not a new block)
            if list_items and line.startswith((" ", "\t")):
                depth, text = list_items[-1]
                list_items[-1] = (depth, f"{text} {inline(line.strip())}")
                i += 1
                continue

            # GFM table: header row + separator row
            if "|" in line and i + 1 < len(lines) and re.match(r"^\s*\|?[\s:|-]+\|[\s:|-]*$", lines[i + 1]):
                flush_paragraph()
                flush_list()
                flush_quote()
                header = [c.strip() for c in line.strip().strip("|").split("|")]
                i += 2
                rows: list[list[str]] = []
                while i < len(lines) and "|" in lines[i] and lines[i].strip():
                    rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                    i += 1
                thead = "".join(f"<th>{inline(c)}</th>" for c in header)
                body = "".join(
                    "<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>" for row in rows
                )
                out.append(f"<table><thead><tr>{thead}</tr></thead><tbody>{body}</tbody></table>")
                continue

            paragraph.append(inline(line.strip()))
            i += 1

        flush_paragraph()
        flush_list()
        flush_quote()
        return "\n".join(out), headings


# ---------------------------------------------------------------------------
# page model + layout
# ---------------------------------------------------------------------------

class Page:
    def __init__(self, group: str, source: Path, title: str, slug: str, body: str, headings):
        self.group = group
        self.source = source
        self.title = title
        self.slug = slug
        self.body = body
        self.headings = headings

    @property
    def href(self) -> str:
        return f"{self.slug}.html"


def layout(*, title: str, prefix: str, nav_html: str, content: str, toc_html: str = "",
           prev_link: str = "", next_link: str = "", suffix: str = "") -> str:
    toc_block = f'<aside class="toc"><p class="toc-title">On this page</p>{toc_html}</aside>' if toc_html else ""
    pager = ""
    if prev_link or next_link:
        pager = f'<nav class="pager">{prev_link}{next_link}</nav>'
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}{(' · ' + esc(SITE_NAME)) if suffix else ''}</title>
<meta name="description" content="Documentation for the {esc(SITE_NAME)}: authentication, 2FA, sessions, OIDC, multi-tenancy and deployment.">
<link rel="icon" href="{prefix}assets/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="{prefix}styles.css">
</head>
<body>
<header class="topbar">
  <button class="nav-toggle" type="button" aria-label="Toggle navigation" aria-expanded="false">☰</button>
  <a class="brand" href="{prefix}index.html">
    <span class="brand-mark">A</span>
    <span class="brand-name">{esc(SITE_NAME)} <span>docs</span></span>
  </a>
  <div class="topbar-links">
    <a href="{prefix}docs/api.html">API reference</a>
    <a href="{REPO}">GitHub</a>
    <button class="theme-toggle" type="button" aria-label="Toggle theme">◐</button>
  </div>
</header>
<div class="shell">
  <nav class="sidebar" aria-label="Documentation">
    {nav_html}
  </nav>
  <main class="content">
    {content}
    {pager}
  </main>
  {toc_block}
</div>
<footer class="footer">
  <span>{esc(SITE_NAME)} · MIT licensed</span>
  <span><a href="{REPO}">github.com/gjovanovicst/golang-auth-api</a></span>
</footer>
<script src="{prefix}main.js"></script>
</body>
</html>
"""


def build_nav(pages: list[Page], active: Page | None, prefix: str) -> str:
    parts: list[str] = []
    for group, label in GROUPS:
        group_pages = [p for p in pages if p.group == group]
        if not group_pages:
            continue
        parts.append(f'<p class="nav-group">{esc(label)}</p><ul>')
        for page in group_pages:
            cls = ' class="active"' if active and page.slug == active.slug else ""
            parts.append(f'<li><a{cls} href="{prefix}{page.href}">{esc(page.title)}</a></li>')
        parts.append("</ul>")
    parts.append('<p class="nav-group">Reference</p><ul>')
    api_cls = ' class="active"' if active is None else ""
    parts.append(f'<li><a{api_cls} href="{prefix}api.html">API reference</a></li>')
    parts.append("</ul>")
    return "".join(parts)


def build_toc(headings, levels=(2, 3)) -> str:
    items = [(lvl, text, hid) for lvl, text, hid in headings if lvl in levels]
    if not items:
        return ""
    out = ["<ul>"]
    for level, text, hid in items:
        cls = ' class="toc-sub"' if level == 3 else ""
        out.append(f'<li{cls}><a href="#{hid}">{esc(text)}</a></li>')
    out.append("</ul>")
    return "".join(out)


def load_pages() -> list[Page]:
    pages: list[Page] = []
    for group, _label in GROUPS:
        directory = SRC / group
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.md")):
            raw = path.read_text(encoding="utf-8")
            match = re.search(r"^#\s+(.+)$", raw, re.MULTILINE)
            title = match.group(1).strip() if match else path.stem
            # strip the leading H1: it becomes the page header
            body = re.sub(r"^#\s+.+\n", "", raw, count=1, flags=re.MULTILINE)
            pages.append(Page(group=group, source=path, title=title, slug=path.stem, body=body, headings=[]))
    return pages


