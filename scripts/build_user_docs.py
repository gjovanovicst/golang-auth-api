def main() -> None:
    if not SRC.is_dir():
        raise SystemExit(f"missing source directory: {SRC}")
    if not SWAGGER.is_file():
        raise SystemExit(f"missing {SWAGGER} — run `make swag-init` first")

    pages = load_pages()
    # keep the numeric prefix out of the slug: 01-quickstart -> quickstart
    for page in pages:
        page.slug = re.sub(r"^\d+-", "", page.source.stem)
    by_name = {p.source.stem: p for p in pages}
    _PAGES_BY_NAME.clear()
    _PAGES_BY_NAME.update(by_name)

    renderer = MarkdownRenderer(by_name)

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for index, page in enumerate(pages):
        body, headings = renderer.render(page.body)
        page.headings = headings
        prev_link = next_link = ""
        if index > 0:
            prev_page = pages[index - 1]
            prev_link = f'<a class="prev" href="{prev_page.href}">← {esc(prev_page.title)}</a>'
        if index + 1 < len(pages):
            next_page = pages[index + 1]
            next_link = f'<a class="next" href="{next_page.href}">{esc(next_page.title)} →</a>'

        content = (
            f'<article><p class="eyebrow">{esc(dict(GROUPS)[page.group])}</p>'
            f"<h1>{esc(page.title)}</h1>{body}</article>"
        )
        nav = build_nav(pages, page, prefix="")
        html_doc = layout(
            title=page.title, prefix="../", nav_html=nav, content=content,
            toc_html=build_toc(headings), prev_link=prev_link, next_link=next_link, suffix="docs",
        )
        (OUT / page.href).write_text(html_doc, encoding="utf-8")

    spec = json.loads(SWAGGER.read_text(encoding="utf-8"))
    api_body, api_headings = render_api(spec)
    api_content = f'<article><p class="eyebrow">Reference</p><h1>API reference</h1>{api_body}</article>'
    (OUT / "api.html").write_text(
        layout(title="API reference", prefix="../", nav_html=build_nav(pages, None, prefix=""),
               content=api_content, toc_html=build_toc(api_headings, levels=(2,)), suffix="API"),
        encoding="utf-8",
    )

    # docs index → first page
    if pages:
        first = pages[0]
        redirect = f'<!DOCTYPE html><meta charset="utf-8"><title>{esc(SITE_NAME)} docs</title>' \
                   f'<meta http-equiv="refresh" content="0; url={first.href}">' \
                   f'<a href="{first.href}">Continue to {esc(first.title)}</a>'
        (OUT / "index.html").write_text(redirect, encoding="utf-8")

    print(f"built {len(pages)} guide pages + api.html into {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
