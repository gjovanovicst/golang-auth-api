# API reference from Swagger 2.0
# ---------------------------------------------------------------------------

def schema_type(schema: dict, spec: dict) -> str:
    if not isinstance(schema, dict):
        return ""
    ref = schema.get("$ref")
    if ref:
        return ref.rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"array&lt;{schema_type(schema.get('items', {}), spec)}&gt;"
    kind = schema.get("type", "")
    if kind == "string" and schema.get("format"):
        return f"string ({schema['format']})"
    return kind


def render_fields(schema: dict, spec: dict, required: list[str] | None = None) -> str:
    if not isinstance(schema, dict):
        return ""
    if "$ref" in schema:
        schema = resolve_ref(schema["$ref"], spec)
    props = schema.get("properties") or {}
    if not props:
        return ""
    required = required if required is not None else schema.get("required", []) or []
    rows = []
    for name, prop in props.items():
        prop = prop or {}
        if "$ref" in prop:
            prop = resolve_ref(prop["$ref"], spec)
        desc = prop.get("description", "")
        marker = ' <span class="req">required</span>' if name in required else ""
        rows.append(
            f"<tr><td><code>{esc(name)}</code>{marker}</td>"
            f"<td>{schema_type(prop, spec)}</td><td>{esc(desc)}</td></tr>"
        )
    return (
        '<table class="fields"><thead><tr><th>Field</th><th>Type</th><th>Description</th></tr></thead>'
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


def resolve_ref(ref: str, spec: dict) -> dict:
    name = ref.rsplit("/", 1)[-1]
    return (spec.get("definitions") or {}).get(name, {})


def render_api(spec: dict) -> tuple[str, list[tuple[int, str, str]]]:
    info = spec.get("info", {})
    host = spec.get("host", "localhost:8080")
    base_path = spec.get("basePath", "/")
    schemes = spec.get("schemes") or ["http"]
    base_url = f"{schemes[0]}://{host}{base_path}".rstrip("/") + "/"

    out: list[str] = []
    headings: list[tuple[int, str, str]] = []

    out.append('<p class="api-lead">Generated from the OpenAPI/Swagger definition that ships with the API '
               f'(<a href="{REPO_BLOB}docs/swagger.json">swagger.json</a>). '
               f'Base URL: <code>{esc(base_url)}</code>.</p>')

    security = spec.get("securityDefinitions") or {}
    if security:
        rows = []
        for name, definition in security.items():
            where = definition.get("in", "")
            key = definition.get("name", "")
            rows.append(f"<tr><td><code>{esc(name)}</code></td><td>{esc(where)}</td><td><code>{esc(key)}</code></td>"
                        f"<td>{esc(definition.get('description', ''))}</td></tr>")
        out.append("<h2 id=\"authentication\">Authentication</h2>")
        headings.append((2, "Authentication", "authentication"))
        out.append('<table><thead><tr><th>Scheme</th><th>In</th><th>Header</th><th>Notes</th></tr></thead>'
                   f"<tbody>{''.join(rows)}</tbody></table>")

    # group operations by tag, preserving order of first appearance
    tagged: dict[str, list[tuple[str, str, dict]]] = {}
    order: list[str] = []
    for path, operations in (spec.get("paths") or {}).items():
        for method, operation in operations.items():
            if method not in METHOD_ORDER or not isinstance(operation, dict):
                continue
            tags = operation.get("tags") or ["other"]
            tag = tags[0]
            if tag not in tagged:
                tagged[tag] = []
                order.append(tag)
            tagged[tag].append((method, path, operation))

    for tag in order:
        anchor = slugify(tag)
        out.append(f'<h2 id="{anchor}">{esc(tag)}</h2>')
        headings.append((2, tag, anchor))
        for method, path, operation in tagged[tag]:
            op_anchor = slugify(f"{method}-{path}")
            summary = operation.get("summary", "")
            description = operation.get("description", "")
            deprecated = ' <span class="deprecated">deprecated</span>' if operation.get("deprecated") else ""
            out.append(
                f'<section class="operation" id="{op_anchor}">'
                f'<h3><span class="method {method}">{method.upper()}</span>'
                f'<code class="path">{esc(path)}</code></h3>'
                f"<p><strong>{esc(summary)}</strong>{deprecated}</p>"
            )
            if description:
                out.append(f"<p>{inline(description)}</p>")

            params = [p for p in operation.get("parameters", []) if isinstance(p, dict)]
            if params:
                rows = []
                for param in params:
                    ptype = param.get("type") or schema_type(param.get("schema", {}), spec)
                    req = "yes" if param.get("required") else "no"
                    rows.append(
                        f"<tr><td><code>{esc(param.get('name', ''))}</code></td>"
                        f"<td>{esc(param.get('in', ''))}</td><td>{req}</td>"
                        f"<td>{esc(ptype)}</td><td>{esc(param.get('description', ''))}</td></tr>"
                    )
                out.append('<table class="params"><thead><tr><th>Name</th><th>In</th><th>Required</th>'
                           f"<th>Type</th><th>Description</th></tr></thead><tbody>{''.join(rows)}</tbody></table>")
                for param in params:
                    if param.get("in") == "body" and param.get("schema"):
                        fields = render_fields(param["schema"], spec)
                        if fields:
                            out.append(f'<p class="fields-title">Body</p>{fields}')

            responses = operation.get("responses") or {}
            if responses:
                rows = []
                for code, response in responses.items():
                    schema = response.get("schema", {}) if isinstance(response, dict) else {}
                    rows.append(
                        f"<tr><td><code>{esc(code)}</code></td>"
                        f"<td>{esc(response.get('description', '') if isinstance(response, dict) else '')}</td>"
                        f"<td>{schema_type(schema, spec)}</td></tr>"
                    )
                out.append('<table class="responses"><thead><tr><th>Status</th><th>Description</th>'
                           f"<th>Schema</th></tr></thead><tbody>{''.join(rows)}</tbody></table>")

            out.append("</section>")
            headings.append((3, f"{method.upper()} {path}", op_anchor))

    return "\n".join(out), headings


