#!/usr/bin/env python3
"""Build the static documentation site under ``site/``.

Sources of truth
----------------
- ``docs/user/<group>/<NN-slug>.md`` — task-oriented guides (Start / Integrate / Deploy)
- ``docs/swagger.json``              — the API reference (generated by ``make swag-init``)

The script has **no third-party dependencies**: the markdown renderer covers the
constructs used in this repository and the API reference is rendered from the
Swagger JSON, so the site builds offline and on any Python 3.9+.

Usage::

    python scripts/build_user_docs.py
    python -m http.server 4173 --directory site   # preview
"""
from __future__ import annotations

import html
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "user"
OUT = ROOT / "site" / "docs"
SWAGGER = ROOT / "docs" / "swagger.json"
SITE = ROOT / "site"

REPO = "https://github.com/gjovanovicst/golang-auth-api"
REPO_BLOB = REPO + "/blob/main/"
SITE_NAME = "Auth API"

GROUPS = [
    ("start", "Start here"),
    ("integrate", "Integrate"),
    ("deploy", "Deploy & operate"),
]

METHOD_ORDER = ["get", "post", "put", "patch", "delete"]


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def esc(value: object) -> str:
    return html.escape(str(value or ""), quote=False)


def slugify(text: str) -> str:
    cleaned = re.sub(r"[`*_~\[\]]", "", text).strip().lower()
    cleaned = re.sub(r"[^a-z0-9]+", "-", cleaned).strip("-")
    return cleaned or "section"


def inline(text: str) -> str:
    """Inline markdown: code, links, bold, italics. HTML is escaped."""
    codes: list[str] = []

    def stash(match: re.Match) -> str:
        codes.append(match.group(1))
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)
    text = html.escape(text, quote=False)
    text = re.sub(
        r"!\[([^\]]*)\]\(([^)\s]+)\)",
        lambda m: (
            f'<img src="{html.escape(resolve_link(m.group(2)), quote=True)}"'
            f' alt="{html.escape(m.group(1), quote=True)}" loading="lazy">'
        ),
        text,
    )
    text = re.sub(
        r"\[([^\]]+)\]\(([^)\s]+)\)",
        lambda m: f'<a href="{html.escape(resolve_link(m.group(2)), quote=True)}">{m.group(1)}</a>',
        text,
    )
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?!\*)", r"<em>\1</em>", text)
    for index, code in enumerate(codes):
        text = text.replace(f"\x00{index}\x00", f"<code>{html.escape(code, quote=False)}</code>")
    return text


_PAGES_BY_NAME: dict[str, "Page"] = {}


def resolve_link(url: str) -> str:
    """Map ``foo.md`` links to generated pages; everything else stays as-is."""
    if re.match(r"^(https?:|mailto:|#)", url):
        return url
    if url.endswith(".md"):
        page = _PAGES_BY_NAME.get(Path(url).stem)
        if page is not None:
            return f"{page.slug}.html"
        return REPO_BLOB + url.lstrip("/")
    return url


